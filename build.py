"""Build a portable index.html from local sources using Python's standard library."""
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parent

def build(check=False):
    template=(ROOT/'index.template.html').read_text(encoding='utf-8')
    css=(ROOT/'styles.css').read_text(encoding='utf-8')
    palette=dict(re.findall(r'(--[\w-]+):\s*(#[a-fA-F0-9]{3,8})\b',css.split('}',1)[0]))
    def colors(markup):
        def replace(match):
            attr,key=match.groups();fallback=palette.get(key,'#4b5b70')
            return f'{attr}="{fallback}" style="{attr}:var({key},{fallback})"'
        return re.sub(r'([\w-]+)="var\((--[\w-]+)\)"',replace,markup)
    definitions=re.search(r'<svg class="svg-definitions".*?</svg>',template,re.S).group(0)
    symbols={key:colors(value) for key,value in re.findall(r'<symbol id="([^"]+)"[^>]*>(.*?)</symbol>',definitions,re.S)}
    gradients=colors(re.search(r'<defs>(.*?)<symbol',definitions,re.S).group(1))
    # Every icon carries its own gradients. No cross-SVG <use> or zero-size defs host.
    icons=r"""(function(global){'use strict';
const symbols=SYMBOLS,gradients=GRADIENTS;let sequence=0;
function render(id){const prefix='w12-icon-'+(++sequence)+'-';const scope=value=>value.replace(/id="([^"]+)"/g,(_,name)=>'id="'+prefix+name+'"').replace(/url\(#([^)]+)\)/g,(_,name)=>'url(#'+prefix+name+')');return '<svg class="app-art" viewBox="0 0 48 48" aria-hidden="true"><defs>'+scope(gradients)+'</defs>'+scope(symbols['i-'+id]||symbols['i-text'])+'</svg>';}
const api={render};if(typeof module!=='undefined'&&module.exports)module.exports=api;else global.Windows12Icons=api;
})(typeof window!=='undefined'?window:globalThis);
""".replace('SYMBOLS',json.dumps(symbols,ensure_ascii=False)).replace('GRADIENTS',json.dumps(gradients,ensure_ascii=False))
    html=template.replace(definitions,'')
    # Expand static symbol instances before adding script contents.
    static_sequence=0
    def static_icon(match):
        nonlocal static_sequence
        static_sequence+=1;attrs,key=match.groups();prefix='w12-static-'+str(static_sequence)+'-'
        markup='<defs>'+gradients+'</defs>'+symbols[key]
        markup=re.sub(r'id="([^"]+)"',lambda item:'id="'+prefix+item[1]+'"',markup)
        markup=re.sub(r'url\(#([^)]+)\)',lambda item:'url(#'+prefix+item[1]+')',markup)
        return '<svg'+attrs+' viewBox="0 0 48 48">'+markup+'</svg>'
    html=re.sub(r'<svg([^>]*)>\s*<use href="#(i-[^"]+)"\s*/>\s*</svg>',static_icon,html)
    paths={key:re.sub(r'\s+id="[^"]+"','',tag) for tag,key in re.findall(r'(<path\s+id="([^"]+)"[^>]*/>)',html)}
    def expand_path(match):
        before,key,after=match.groups()
        if key not in paths:raise ValueError('Unknown SVG use: '+key)
        return '<g'+before+after+'>'+paths[key]+'</g>'
    html=re.sub(r'<use\s+([^>]*?)href="#([^"]+)"([^>]*?)/>',expand_path,html)
    html=colors(html)
    # Inlined code runs at the end of body, after all DOM nodes exist.
    scripts=[]
    def collect(match):
        source=match.group(1);content=icons if source=='icons.js' else (ROOT/source).read_text(encoding='utf-8')
        scripts.append('<script data-source="'+source+'">\n'+re.sub(r'</script',r'<\\/script',content,flags=re.I)+'\n</script>');return ''
    html=re.sub(r'\s*<script defer src="\./([^"?]+)"></script>',collect,html)
    html=html.replace('<link rel="stylesheet" href="./styles.css">','<style data-source="styles.css">\n'+css+'\n</style>')
    html=html.replace('</body>','\n'+'\n'.join(scripts)+'\n</body>')
    html=html.replace('<!doctype html>','<!doctype html>\n<!-- Generated by build.py from index.template.html and local source files. -->',1)
    outputs={'icons.js':icons,'index.html':html}
    for name,content in outputs.items():
        path=ROOT/name
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=content:raise SystemExit(name+' is out of date; run python -B build.py')
        else:path.write_text(content,encoding='utf-8')
    print('Portable HTML is current.' if check else 'Built index.html and icons.js (self-contained, no startup resource requests).')
if __name__=='__main__':build('--check' in sys.argv)
